#!/usr/bin/env node
// npm run benchmark — loads the same Todo app four ways in headless Chrome and measures requests,
// bytes and times:
//   next-bundles   UI5 Next, dist/bundles  (dist/demo/bundles/index.html)
//   next-esm       UI5 Next, dist/esm      (dist/demo/esm/index.html)
//   classic-cdn    classic UI5 (AMD, ui5loader, bootstrap tag) with the optimized CDN build of the
//                  same version (sap-ui-core.js + library-preload.js), mirrored locally on first use
//   classic-src    classic UI5 from the npm sources without a build step (what you get without
//                  the UI5 tooling; theme CSS and library manifests taken from dist/esm)
// All variants are served by the same local server (HTTP/2 + TLS + gzip), a fresh browser context
// per run, cache disabled. Profiles: "local" (no throttling) and "4g" (40 ms RTT, 20 Mbit/s down,
// 5 Mbit/s up). Results: bench/results.json and bench/results.md.
// Usage: node scripts/benchmark.mjs [--runs 5] [--profiles local,4g] [--variants next-bundles,...]
import { spawn, spawnSync } from "node:child_process";
import fs from "node:fs";
import http2 from "node:http2";
import os from "node:os";
import path from "node:path";
import zlib from "node:zlib";
import { parseArgs } from "node:util";
import { fileURLToPath } from "node:url";
import { MIME } from "../src/serve.mjs";
import { findBrowser } from "./demo-check.mjs";

const root = fileURLToPath(new URL("..", import.meta.url));
const { values: args } = parseArgs({
	options: {
		runs: { type: "string", default: "5" },
		profiles: { type: "string", default: "local,4g" },
		variants: { type: "string", default: "next-bundles,next-esm,classic-cdn,classic-src" },
	},
});
const RUNS = Number(args.runs);
const VERSION = JSON.parse(fs.readFileSync(path.join(root, "src/packages.json"), "utf8")).ui5Version;
const CDN = `https://sdk.openui5.org/${VERSION}/resources/`;
const MIRROR = path.join(root, ".cache", "openui5-cdn", VERSION);
const PROFILES = {
	local: null,
	"4g": { offline: false, latency: 40, downloadThroughput: (20 * 1024 * 1024) / 8, uploadThroughput: (5 * 1024 * 1024) / 8 },
};
const VARIANTS = {
	"next-bundles": { label: "UI5 Next, bundles/", url: "/dist/demo/bundles/index.html" },
	"next-esm": { label: "UI5 Next, esm/", url: "/dist/demo/esm/index.html" },
	"classic-cdn": { label: "classic UI5, CDN build", url: "/classic-cdn/index.html" },
	"classic-src": { label: "classic UI5, npm sources (no build)", url: "/classic-src/index.html" },
};

// ---------- server ----------
const packageSrcDirs = fs.readdirSync(path.join(root, "node_modules/@openui5")).sort()
	.map((p) => path.join(root, "node_modules/@openui5", p, "src")).filter((d) => fs.existsSync(d));
const exists = (f) => fs.existsSync(f) && fs.statSync(f).isFile();

async function mirrorFile(rel) {
	const file = path.join(MIRROR, rel);
	if (exists(file)) return file;
	if (exists(file + ".404")) return null;
	const res = await fetch(CDN + rel);
	fs.mkdirSync(path.dirname(file), { recursive: true });
	if (!res.ok) {
		fs.writeFileSync(file + ".404", String(res.status));
		return null;
	}
	fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
	return file;
}

async function resolveFile(pathname) {
	const clean = path.posix.normalize(pathname);
	if (clean.includes("..")) return null;
	let m;
	if ((m = /^\/dist\/(.*)$/.exec(clean))) return path.join(root, "dist", m[1]);
	if ((m = /^\/classic-cdn\/resources\/(.*)$/.exec(clean))) return mirrorFile(m[1]);
	if ((m = /^\/classic-src\/resources\/(.*)$/.exec(clean))) {
		for (const dir of packageSrcDirs) if (exists(path.join(dir, m[1]))) return path.join(dir, m[1]);
		// generated by the UI5 tooling (theme CSS, library manifests, version info): take UI5 Next's
		if (!m[1].endsWith(".js")) return path.join(root, "dist/esm", m[1]);
		return null;
	}
	if ((m = /^\/classic-(?:cdn|src)\/(.*)$/.exec(clean))) return path.join(root, "bench/classic", m[1] || "index.html");
	return null;
}

const gzipCache = new Map();
function certificate() {
	const dir = path.join(root, ".cache", "bench-cert");
	const key = path.join(dir, "key.pem");
	const cert = path.join(dir, "cert.pem");
	if (!exists(key)) {
		fs.mkdirSync(dir, { recursive: true });
		const r = spawnSync("openssl", ["req", "-x509", "-newkey", "rsa:2048", "-nodes", "-keyout", key, "-out", cert, "-days", "30", "-subj", "/CN=localhost"], { encoding: "utf8" });
		if (r.status !== 0) throw new Error("openssl failed: " + r.stderr);
	}
	return { key: fs.readFileSync(key), cert: fs.readFileSync(cert) };
}

async function startServer() {
	const server = http2.createSecureServer({ ...certificate(), allowHTTP1: true }, async (req, res) => {
		const pathname = decodeURIComponent(new URL(req.url, "https://localhost").pathname);
		const file = await resolveFile(pathname).catch(() => null);
		if (!file || !exists(file)) {
			res.writeHead(404, { "cache-control": "no-store" });
			return res.end();
		}
		const type = MIME[path.extname(file).toLowerCase()] ?? "application/octet-stream";
		const headers = { "content-type": type, "cache-control": "no-store" };
		let body = fs.readFileSync(file);
		if (/gzip/.test(req.headers["accept-encoding"] ?? "") && /text|javascript|json|xml|svg/.test(type) && body.length > 1024) {
			const key = file + ":" + fs.statSync(file).mtimeMs;
			if (!gzipCache.has(key)) gzipCache.set(key, zlib.gzipSync(body, { level: 6 }));
			body = gzipCache.get(key);
			headers["content-encoding"] = "gzip";
		}
		res.writeHead(200, headers);
		res.end(body);
	});
	await new Promise((r) => server.listen(0, r));
	return server;
}

// ---------- browser ----------
async function startChrome(browser) {
	const profile = fs.mkdtempSync(path.join(os.tmpdir(), "ui5next-bench-"));
	const child = spawn(browser, [
		"--headless=new", "--remote-debugging-port=0", `--user-data-dir=${profile}`, "--ignore-certificate-errors",
		"--no-first-run", "--no-default-browser-check", "--window-size=1200,800", "about:blank",
	], { stdio: ["ignore", "ignore", "pipe"] });
	const wsUrl = await new Promise((resolve, reject) => {
		let buf = "";
		child.stderr.on("data", (d) => {
			buf += d;
			const m = buf.match(/DevTools listening on (ws:\/\/\S+)/);
			if (m) resolve(m[1]);
		});
		setTimeout(() => reject(new Error("chrome did not start")), 20000);
	});
	const ws = new WebSocket(wsUrl);
	await new Promise((r) => ws.addEventListener("open", r));
	let id = 0;
	const pending = new Map();
	const listeners = new Set();
	ws.addEventListener("message", (ev) => {
		const msg = JSON.parse(ev.data);
		if (msg.id && pending.has(msg.id)) {
			const { resolve, reject } = pending.get(msg.id);
			pending.delete(msg.id);
			msg.error ? reject(new Error(msg.error.message)) : resolve(msg.result);
		} else for (const l of listeners) l(msg);
	});
	const send = (method, params = {}, sessionId) => new Promise((resolve, reject) => {
		const i = ++id;
		pending.set(i, { resolve, reject });
		ws.send(JSON.stringify({ id: i, method, params, sessionId }));
	});
	return {
		send, listeners,
		close: async () => {
			ws.close();
			child.kill();
			await new Promise((r) => child.once("exit", r));
			try {
				fs.rmSync(profile, { recursive: true, force: true, maxRetries: 5 });
			} catch {
				/* temp */
			}
		},
	};
}

const READY_SCRIPT = `(() => {
	const mark = () => {
		const li = document.querySelector("li.sapMLIB");
		const title = document.querySelector(".sapMTitle");
		if (li && title && title.textContent.includes("Todo") && !window.__readyAt) window.__readyAt = performance.now();
	};
	new MutationObserver(mark).observe(document, { subtree: true, childList: true });
})();`;

const kindOf = (url, type) => {
	if (/\.woff2?(\?|$)/.test(url)) return "fonts";
	if (type === "Stylesheet" || /\.css(\?|$)/.test(url)) return "css";
	if (/\.js(\?|$)/.test(url)) return "js"; // by extension: a JSON module import has type "Script" too
	if (/\/(demo|classic-(cdn|src))\/(?!resources)/.test(url) || /\/dist\/demo\//.test(url)) return "app";
	return "data"; // json, properties, xml, CLDR, manifests
};

async function measure(chrome, base, variant, profile) {
	const { send, listeners } = chrome;
	const { browserContextId } = await send("Target.createBrowserContext");
	const { targetId } = await send("Target.createTarget", { url: "about:blank", browserContextId });
	const { sessionId } = await send("Target.attachToTarget", { targetId, flatten: true });
	const s = (m, p) => send(m, p, sessionId);
	const requests = new Map();
	const errors = [];
	const listener = (msg) => {
		if (msg.sessionId !== sessionId) return;
		const p = msg.params;
		if (msg.method === "Network.requestWillBeSent") requests.set(p.requestId, { url: p.request.url, type: p.type, bytes: 0, status: 0 });
		else if (msg.method === "Network.responseReceived" && requests.has(p.requestId)) requests.get(p.requestId).status = p.response.status;
		else if (msg.method === "Network.loadingFinished" && requests.has(p.requestId)) requests.get(p.requestId).bytes = p.encodedDataLength;
		else if (msg.method === "Runtime.exceptionThrown") errors.push(p.exceptionDetails.exception?.description ?? p.exceptionDetails.text);
	};
	listeners.add(listener);
	await s("Network.enable");
	await s("Runtime.enable");
	await s("Page.enable");
	await s("Performance.enable");
	await s("Network.setCacheDisabled", { cacheDisabled: true });
	if (PROFILES[profile]) await s("Network.emulateNetworkConditions", PROFILES[profile]);
	await s("Page.addScriptToEvaluateOnNewDocument", { source: READY_SCRIPT });
	const evaluate = async (expression) => (await s("Runtime.evaluate", { expression, returnByValue: true })).result.value;

	await s("Page.navigate", { url: base + VARIANTS[variant].url });
	const t0 = Date.now();
	let readyAt = null;
	while (Date.now() - t0 < 120000) {
		readyAt = await evaluate("window.__readyAt ?? null").catch(() => null);
		if (readyAt) break;
		await new Promise((r) => setTimeout(r, 100));
	}
	// network idle: no new request for 1.5 s (lazy loading after the first render)
	let count = -1;
	for (let i = 0; i < 40 && count !== requests.size; i++) {
		count = requests.size;
		await new Promise((r) => setTimeout(r, 1500));
	}
	const timing = await evaluate(`(() => {
		const n = performance.getEntriesByType("navigation")[0];
		const fcp = performance.getEntriesByName("first-contentful-paint")[0];
		return {
			domContentLoaded: n.domContentLoadedEventEnd, load: n.loadEventEnd, fcp: fcp ? fcp.startTime : null,
			timeline: performance.getEntriesByType("resource").map((r) => [Math.round(r.startTime), Math.round(r.responseEnd), r.name.replace(location.origin, "").replace(/\\?.*$/, "")]),
		};
	})()`);
	const metrics = Object.fromEntries((await s("Performance.getMetrics")).metrics.map((m) => [m.name, m.value]));
	listeners.delete(listener);
	await send("Target.closeTarget", { targetId });
	await send("Target.disposeBrowserContext", { browserContextId });

	const list = [...requests.values()].filter((r) => !r.url.startsWith("data:") && !/favicon/.test(r.url));
	const byKind = {};
	for (const r of list) {
		const k = kindOf(r.url, r.type);
		byKind[k] ??= { requests: 0, bytes: 0 };
		byKind[k].requests++;
		byKind[k].bytes += r.bytes;
	}
	return {
		ok: !!readyAt,
		ready: readyAt,
		...timing,
		requests: list.length,
		failed: list.filter((r) => r.status >= 400).length,
		bytes: list.reduce((a, r) => a + r.bytes, 0),
		byKind,
		scriptMs: metrics.ScriptDuration * 1000,
		taskMs: metrics.TaskDuration * 1000,
		heapMiB: metrics.JSHeapUsedSize / 1024 / 1024,
		errors: errors.slice(0, 3),
		urls: list.map((r) => `${kindOf(r.url, r.type).padEnd(5)} ${String(Math.round(r.bytes / 1024)).padStart(5)} KiB  ${r.url.replace(/^https:\/\/localhost:\d+/, "").replace(/\?.*$/, "")}`),
	};
}

const median = (xs) => {
	const v = xs.filter((x) => x != null).sort((a, b) => a - b);
	return v.length ? v[Math.floor((v.length - 1) / 2)] : null;
};

// ---------- main ----------
const browser = findBrowser();
if (!browser) {
	console.log("benchmark skipped: no Chrome/Chromium found (set CHROME_BIN)");
	process.exit(0);
}
if (!fs.existsSync(path.join(root, "dist/demo/bundles/index.html"))) {
	console.error("run npm run build first");
	process.exit(1);
}
const server = await startServer();
const base = `https://localhost:${server.address().port}`;
const chrome = await startChrome(browser);
const variants = args.variants.split(",");
const profiles = args.profiles.split(",");
const results = { ui5Version: VERSION, date: new Date().toISOString(), runs: RUNS, server: "local node:http2 (TLS, gzip level 6), cache disabled", profiles: PROFILES, browser, results: {} };

for (const profile of profiles) {
	for (const variant of variants) {
		process.stdout.write(`${profile.padEnd(6)} ${variant.padEnd(13)} warm-up`);
		await measure(chrome, base, variant, "local"); // fills the CDN mirror and the gzip cache
		const runs = [];
		for (let i = 0; i < RUNS; i++) {
			runs.push(await measure(chrome, base, variant, profile));
			process.stdout.write(runs.at(-1).ok ? " ." : " x");
		}
		const pick = (k) => median(runs.map((r) => r[k]));
		const kinds = [...new Set(runs.flatMap((r) => Object.keys(r.byKind)))];
		const summary = {
			label: VARIANTS[variant].label,
			ok: runs.every((r) => r.ok),
			ready: pick("ready"), fcp: pick("fcp"), domContentLoaded: pick("domContentLoaded"), load: pick("load"),
			requests: pick("requests"), failed: pick("failed"), bytes: pick("bytes"),
			scriptMs: pick("scriptMs"), taskMs: pick("taskMs"), heapMiB: pick("heapMiB"),
			byKind: Object.fromEntries(kinds.map((k) => [k, { requests: median(runs.map((r) => r.byKind[k]?.requests ?? 0)), bytes: median(runs.map((r) => r.byKind[k]?.bytes ?? 0)) }])),
			errors: [...new Set(runs.flatMap((r) => r.errors))],
			requestList: runs[0].urls, // first run
			timeline: runs[0].timeline, // first run: [start, end, url]
		};
		(results.results[profile] ??= {})[variant] = summary;
		console.log(`  ready ${summary.ready?.toFixed(0)} ms, ${summary.requests} requests, ${(summary.bytes / 1024 / 1024).toFixed(2)} MiB`);
	}
}
await chrome.close();
server.close();

// ---------- report ----------
const ms = (x) => (x == null ? "—" : `${Math.round(x).toLocaleString("en-US")} ms`);
const mib = (x) => `${(x / 1024 / 1024).toFixed(2)} MiB`;
let md = `# Benchmark: the same Todo app, four ways\n\nOpenUI5 ${VERSION}, ${results.date.slice(0, 10)}, median of ${RUNS} runs, headless Chrome, ${results.server}.\n`;
md += `Profiles: **local** = no throttling; **4g** = 40 ms RTT, 20 Mbit/s down, 5 Mbit/s up (CPU not throttled).\n`;
md += `"ready" = first rendered list item (app usable); bytes = transferred (gzip).\n`;
for (const profile of profiles) {
	md += `\n## ${profile}\n\n| | ready | first paint | DOMContentLoaded | load | requests | transferred | script | heap |\n|---|---|---|---|---|---|---|---|---|\n`;
	for (const [, r] of Object.entries(results.results[profile])) {
		md += `| ${r.label}${r.ok ? "" : " (failed)"} | **${ms(r.ready)}** | ${ms(r.fcp)} | ${ms(r.domContentLoaded)} | ${ms(r.load)} | ${r.requests} | ${mib(r.bytes)} | ${ms(r.scriptMs)} | ${r.heapMiB.toFixed(0)} MiB |\n`;
	}
	md += `\nRequests by kind (count / transferred):\n\n| | js | css | data | fonts | app |\n|---|---|---|---|---|---|\n`;
	for (const [, r] of Object.entries(results.results[profile])) {
		const c = (k) => (r.byKind[k] ? `${r.byKind[k].requests} / ${(r.byKind[k].bytes / 1024).toFixed(0)} KiB` : "0");
		md += `| ${r.label} | ${c("js")} | ${c("css")} | ${c("data")} | ${c("fonts")} | ${c("app")} |\n`;
	}
}
fs.mkdirSync(path.join(root, "bench"), { recursive: true });
fs.writeFileSync(path.join(root, "bench/results.json"), JSON.stringify(results, null, 2) + "\n");
fs.writeFileSync(path.join(root, "bench/results.md"), md);
console.log("\n" + md);
