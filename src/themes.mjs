// Theme build: compiles library.source.less -> library.css (+ library-parameters.json) with
// the LESS compiler that UI5 itself ships (sap/ui/thirdparty/less.js, LESS 1.6.3), run in a
// node:vm context. This replaces the part of the UI5 tooling (less-openui5) that UI5 needs
// at runtime: the CSS, the inline theme parameters and library-parameters.json.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

/** Load the bundled LESS compiler from its (classic) source. */
export function loadLess(lessSource) {
	const loc = { href: "http://localhost/", protocol: "http:", hostname: "localhost", port: "" };
	const win = { location: loc, document: { getElementsByTagName: () => [], location: loc }, less: { env: "production", async: false, fileAsync: false } };
	win.window = win;
	const ctx = vm.createContext({ window: win, document: win.document, location: loc, navigator: { userAgent: "node" }, console, setTimeout, clearTimeout, XMLHttpRequest: function () {} });
	vm.runInContext(lessSource, ctx, { filename: "less.js" });
	const less = win.less;
	if (!less?.Parser) throw new Error("bundled less.js did not initialise");
	return less;
}

/**
 * Compile one library theme.
 * @param less compiler from loadLess()
 * @param {string} entry absolute path of library.source.less
 * @returns {Promise<{css: string, parameters: object}>}
 */
export function compileTheme(less, entry) {
	const entryDir = path.dirname(entry) + path.sep;
	less.Parser.fileLoader = (file, info, callback) => {
		const abs = path.resolve(info.currentDirectory || entryDir, file);
		let data;
		try {
			data = fs.readFileSync(abs, "utf8");
		} catch {
			return callback({ type: "File", message: `cannot read ${abs}` });
		}
		const dir = path.dirname(abs) + path.sep;
		let rootpath = path.relative(entryDir, dir).split(path.sep).join("/");
		if (rootpath) rootpath += "/";
		callback(null, data, abs, {
			currentDirectory: dir, filename: abs, entryPath: entryDir, rootFilename: entry,
			rootpath, relativeUrls: true,
		});
	};
	const fileInfo = { currentDirectory: entryDir, filename: entry, entryPath: entryDir, rootpath: "", rootFilename: entry, relativeUrls: true };
	return new Promise((resolve, reject) => {
		const parser = new less.Parser({ filename: entry, paths: [entryDir], relativeUrls: true, rootpath: "", currentFileInfo: fileInfo });
		parser.parse(fs.readFileSync(entry, "utf8"), (err, tree) => {
			if (err) return reject(new Error(`${err.message} (${err.filename}:${err.line})`));
			try {
				const root = tree.eval(new less.tree.evalEnv({}, [tree]));
				const parameters = {};
				for (const r of root.rules) {
					if (!r.variable || typeof r.name !== "string") continue;
					try {
						parameters[r.name.slice(1)] = r.value.toCSS({ compress: false });
					} catch {
						/* not a plain value (detached ruleset, mixin call, ...) */
					}
				}
				resolve({ css: tree.toCSS({}), parameters });
			} catch (e) {
				reject(new Error(`${e.message}${e.filename ? ` (${e.filename}:${e.line})` : ""}`));
			}
		});
	});
}

/** The rules less-openui5 appends: inline parameters and theme metadata. */
export function themeFooter(libName, themeName, version, parameters) {
	const id = libName.replace(/\./g, "\\.");
	const params = encodeURIComponent(JSON.stringify(parameters)).replace(/'/g, "%27");
	// read back with decodeURI(), so it stays plain JSON (no quotes or parentheses in it)
	const meta = JSON.stringify({ Path: `UI5.${libName.replace(/\./g, "/")}.${themeName}`, PathPattern: "/%frameworkId%/%libId%/%themeId%/%fileId%.css", Version: version });
	return (
		`\n/* Inline theming parameters (generated by ui5-next) */\n` +
		`#sap-ui-theme-${id}{background-image:url('data:text/plain;utf-8,${params}')}\n` +
		`.sapThemeMetaData-UI5-${libName.replace(/\./g, "-")}{background-image:url('data:text/plain;utf-8,${meta}')}\n`
	);
}

/**
 * Find library themes in the output tree: <lib path>/themes/<theme>/library.source.less
 * @returns {{lib: string, theme: string, dir: string}[]}
 */
export function findThemes(treeKeys) {
	const out = [];
	for (const rel of treeKeys) {
		const m = /^(.+)\/themes\/([^/]+)\/library\.source\.less$/.exec(rel);
		if (m) out.push({ lib: m[1].replace(/\//g, "."), theme: m[2], dir: `${m[1]}/themes/${m[2]}` });
	}
	return out;
}
